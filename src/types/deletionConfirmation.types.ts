/**
 * 削除の確認で「利用者に見せた件数」を運ぶ形（docs/remaining-work.md 段階26）。
 *
 * 削除の確認は「消すと何を巻き添えにするか」を数えて見せる。数え終わってから
 * 利用者が押すまでの間に、他の教員が書き足す窓がある。そこで**見せた件数を削除の
 * 要求に添えて渡し、main が消す直前に数え直して、増えていれば中止する**。
 *
 * これは main の状態を renderer から運び戻しているのではない。運んでいるのは
 * **利用者が何を見て決めたか**であり、削除という意図の一部である
 * （docs/coding-style.md「IPC は意図を運ぶ」）。main は渡された件数を DB へ
 * 書かないし、数え直しの結果としても採らない。突き合わせにだけ使う。
 */

/** 削除の確認で利用者に見せた、巻き添えになるもの1種類ぶんの件数 */
export interface ConfirmedDeletionCount {
  /**
   * 数えたものの名前。画面に出す文言であり、数え直しとの突き合わせの鍵でもある。
   *
   * 綴りが食い違うと突き合わせが素通りするので、**名前は必ず
   * `src/lib/shared/deletionCountNames.ts` の `DELETION_COUNT_NAME` から採る**
   * （main と renderer の双方が同じ宣言を値で引ける唯一の場所）。
   */
  countedName: string
  /** そのとき画面に出ていた件数 */
  shownCount: number
}

/**
 * 設定画面の使い方ガイド。**いまは「同期設定」のタブだけを扱う。**
 *
 * 設定のほかのタブ（キーボード・表示など）は、その場で見て分かる設定の並びなので
 * 手引きを持たない。同期だけは、知らないまま使うとデータが消えたように見えるうえ、
 * 使い始めるまでに画面の外での用意（共有フォルダ）と順序がある。
 *
 * **同期設定のタブに常設している注意事項（`SyncNotes`）とは重ねない。** あちらは
 * 「何に気をつけるか」、こちらは「どう使うか」（始め方・合流のしかた・分担の進め方）を書く。
 *
 * 書いてある挙動は、すべて実装で確かめたもの（推論した手順は書かない）:
 * - 共有フォルダの追加・空のフォルダでの2択・合流 — `SharedFolderConnectDialog.tsx`、
 *   `electron-src/lib/sync/sharedProfileSetup.ts`
 * - 起動するデータの切り替えとローカルへの移行 — `StorageProfileList.tsx`、
 *   `electron-src/lib/sync/storageModeService.ts`。根は起動時に1度だけ決まる
 *   （`electron-src/lib/storageRoots.ts`）
 * - 合流したPCのローカルのデータを統合しないこと — `sharedProfileSetup.ts` の合流
 * - 同期1回は「相手の写しを読む → 自分の写しを置く」の順 — sqlite-nas-sync の `syncNow`
 * - 採点が先生ごとに別の行になること — `QuestionScore.userId`
 * - 届いた内容で開いている画面を取り直さないこと — `src/queries/queryClient.ts`
 */

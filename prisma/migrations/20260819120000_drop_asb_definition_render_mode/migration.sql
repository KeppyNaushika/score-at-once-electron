-- AsbDefinition.renderMode（解答用紙／模範解答の描き分け）を落とす。
--
-- この列は「その解答用紙を最後にどちらの姿で見ていたか」を持っていた。しかし
-- 描き分けは**見る人の作業の状態**であって、解答用紙が持つ性質ではない。同じ
-- 解答用紙を開いた別の教員が、前の人の見方に引きずられる理由は無い。
--
-- 行き先は利用者の設定（UserPreference.asbRenderMode）。書き出しは常に解答用紙と
-- 模範解答の両方を出すようになったため、出力の姿を決めるのにもこの列は要らない
-- （試験変換は元から両方を描いていた）。
--
-- 列を落とすだけで失われる情報は上記の「最後の見方」のみ。
ALTER TABLE "AsbDefinition" DROP COLUMN "renderMode";
